#!/usr/bin/env python3
"""Normalize JSON results into comparison tables (markdown + CSV)."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any


def load(path: Path) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def forge_rows(data: dict[str, Any], source: str) -> list[dict[str, Any]]:
    rows = []
    for r in data.get("results", []):
        rows.append(
            {
                "runtime": "forge",
                "source": source,
                "dtype": r.get("dtype") or data.get("dtype"),
                "batch": r.get("admit_batch"),
                "max_new": r.get("max_new") or data.get("max_new"),
                "workload": r.get("workload") or data.get("workload"),
                "aggregate_tok_s": r.get("aggregate_tok_s_median"),
                "decode_tok_s": r.get("steady_decode_tok_s_median"),
                "prefill_tok_s": r.get("prefill_tok_s_median"),
                "ttft_p50_s": r.get("ttft_p50_median_s"),
                "e2e_p50_s": r.get("e2e_p50_median_s"),
                "occupancy": r.get("avg_occupancy_median"),
            }
        )
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="benchmarks/results/local")
    ap.add_argument("--out-md", default="benchmarks/results/local/comparison.md")
    ap.add_argument("--out-csv", default="benchmarks/results/local/comparison.csv")
    args = ap.parse_args()
    root = Path(args.results_dir)

    rows: list[dict[str, Any]] = []
    for p in sorted(root.glob("forge_*.json")):
        data = load(p)
        if data:
            rows.extend(forge_rows(data, p.name))

    vllm = load(root / "vllm_short.json")
    if vllm and vllm.get("status") != "unavailable":
        for r in vllm.get("results", []):
            rows.append(
                {
                    "runtime": "vllm",
                    "source": "vllm_short.json",
                    "dtype": r.get("dtype") or vllm.get("precision"),
                    "batch": r.get("batch"),
                    "max_new": 16,
                    "workload": "short_hello",
                    "aggregate_tok_s": r.get("aggregate_tok_s"),
                    "decode_tok_s": None,
                    "prefill_tok_s": None,
                    "ttft_p50_s": None,
                    "e2e_p50_s": None,
                    "occupancy": None,
                }
            )

    blocker = load(root / "vllm_blocker.json")
    llama = load(root / "llama_cpp_short_f16.json")

    out_csv = Path(args.out_csv)
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "runtime",
        "source",
        "dtype",
        "batch",
        "max_new",
        "workload",
        "aggregate_tok_s",
        "decode_tok_s",
        "prefill_tok_s",
        "ttft_p50_s",
        "e2e_p50_s",
        "occupancy",
    ]
    with out_csv.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k) for k in fields})

    lines = [
        "# comparison summary",
        "",
        "Auto-generated by `benchmarks/analysis/summarize_results.py`.",
        "",
        "| runtime | dtype | batch | max_new | workload | agg tok/s | decode | TTFT p50 |",
        "|---|---|---:|---:|---|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            "| {runtime} | {dtype} | {batch} | {max_new} | {workload} | {aggregate_tok_s} | {decode_tok_s} | {ttft_p50_s} |".format(
                runtime=r.get("runtime"),
                dtype=r.get("dtype"),
                batch=r.get("batch"),
                max_new=r.get("max_new"),
                workload=r.get("workload"),
                aggregate_tok_s=_fmt(r.get("aggregate_tok_s")),
                decode_tok_s=_fmt(r.get("decode_tok_s")),
                ttft_p50_s=_fmt(r.get("ttft_p50_s")),
            )
        )
    lines.append("")
    if llama:
        lines.append(f"- llama.cpp commit: `{llama.get('commit')}` precision={llama.get('precision')}")
    if blocker:
        lines.append(f"- vLLM unavailable: {blocker.get('reason')}")
    elif vllm:
        lines.append(f"- vLLM version: {vllm.get('version')}")
    Path(args.out_md).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out_csv} and {args.out_md} ({len(rows)} rows)")
    return 0


def _fmt(v: Any) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.2f}"
    return str(v)


if __name__ == "__main__":
    raise SystemExit(main())
